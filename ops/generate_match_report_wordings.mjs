// Writes the app's match report wordings from their one source, the JSON the
// public site reads too (decision package 12, PLM-07), so the app's draft and
// the public live report word events alike.
//
//   node ops/generate_match_report_wordings.mjs
//
// Source: public-site/lib/match-report-wordings.json (inside public-site, as
// only that folder is deployed with the site).
// Output: lib/src/features/match_workspace/match_report_wordings.dart.
// test/match_report_wordings_sync_test.dart fails when the two differ.
import fs from 'node:fs';

const root = new URL('..', import.meta.url);
const source = new URL('public-site/lib/match-report-wordings.json', root);
const target = new URL('lib/src/features/match_workspace/match_report_wordings.dart', root);

// The JSON's keys and the Dart names, in the file's order.
export const names = {
  intros: 'reportIntros',
  assists: 'reportAssists',
  goalsUs: 'reportGoalsUs',
  goalsThem: 'reportGoalsThem',
  shotsUs: 'reportShotsUs',
  shotsThem: 'reportShotsThem',
  saves: 'reportSaves',
  penaltiesUs: 'reportPenaltiesUs',
  penaltiesThem: 'reportPenaltiesThem',
  cardsUs: 'reportCardsUs',
  cardsThem: 'reportCardsThem',
  substitutions: 'reportSubstitutions',
  injuries: 'reportInjuries',
};

const dartString = value => `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'").replaceAll('$', '\\$')}'`;
const dartList = (values, indent) =>
  `[\n${values.map(v => `${indent}  ${dartString(v)},`).join('\n')}\n${indent}]`;

const json = JSON.parse(fs.readFileSync(source, 'utf8'));
const parts = [];
for (const [key, name] of Object.entries(names)) {
  const value = json[key];
  if (value === undefined) throw new Error(`missing ${key}`);
  if (Array.isArray(value)) {
    parts.push(`const ${name} = ${dartList(value, '')};`);
  } else {
    const entries = Object.entries(value).map(([group, list]) => `  ${dartString(group)}: ${dartList(list, '  ')},`);
    parts.push(`const ${name} = {\n${entries.join('\n')}\n};`);
  }
}
const unknown = Object.keys(json).filter(key => key !== 'about' && !(key in names));
if (unknown.length) throw new Error(`unknown keys: ${unknown.join(', ')}`);

fs.writeFileSync(target, `// Generated by ops/generate_match_report_wordings.mjs from
// public-site/lib/match-report-wordings.json. Change the JSON and run the
// script; do not edit this file.

/// The wordings of a match report from its events, as a reporter would
/// put them: several for each kind of event, each telling only what was
/// registered. Placeholders: {min} the minute as an ordinal ("20:e"), {n}
/// the minute as a number, {p} the player, {t} our team, {tg} our team as
/// owner ("hemmalagets"), {o} the opponent, {od} the opponent as a side
/// ("gästerna"), {og} the opponent as owner ("gästernas"), {s} the score,
/// {a} an assist, {in}/{out} a substitution, {home} where it was played.
library;

${parts.join('\n\n')}
`);
console.log('ok');
